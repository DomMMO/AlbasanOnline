# Each mob's body for keeping mobs apart: a flat oval at its feet, inside its own picture (a little
# narrower than its hurtbox, half as deep as wide), from characters/hitboxes.json.
#   python tools/mob_bodies.py
#     -> ../shared/src/data/mobBodies.ts   (the server keeps these ovals apart)
#     -> characters/mobs/<id>.tscn         (the same oval as an Area2D "Govde", seen in the editor)
# The scenes are edited as text so nothing else in them changes (a scene whose art is missing on
# this machine would lose its sprite if Godot loaded and saved it again).
import json, random, re

WIDTH_SHARE = 0.4   # half-width of the oval / width of the hurtbox
MAX_RX = 40.0
BODY_LAYER = 4

boxes = json.load(open("characters/hitboxes.json", encoding="utf-8"))
bodies = {}
for key in sorted(boxes):
    if key.startswith("mobs/"):
        w = float(boxes[key]["hurtbox"][2])
        rx = round(min(MAX_RX, max(4.0, w * WIDTH_SHARE)), 1)
        bodies[key[5:]] = (rx, round(rx / 2, 1))

rows = [f"  {mob}: {{ rx: {rx}, ry: {ry} }}," for mob, (rx, ry) in bodies.items()]
out = """// Generated by yeni-oyun-projesi/tools/mob_bodies.py from characters/hitboxes.json: each mob's
// body, a flat oval at its feet (half-width rx, half-height ry, in pixels) inside its own picture.
// Mobs keep their ovals apart so they don't stack on one another.

export interface MobBody {
  rx: number;
  ry: number;
}

export const MOB_BODIES: Record<string, MobBody> = {
""" + "\n".join(rows) + """
};

/** A mob's body oval (a small one for a mob the table doesn't know). */
export function mobBody(mobId: string): MobBody {
  return MOB_BODIES[mobId] ?? { rx: 6, ry: 3 };
}
"""
open("../shared/src/data/mobBodies.ts", "w", encoding="utf-8", newline="\n").write(out)

rng = random.Random(4417)
scenes = 0
for mob, (rx, ry) in bodies.items():
    path = f"characters/mobs/{mob}.tscn"
    try:
        text = open(path, encoding="utf-8").read()
    except FileNotFoundError:
        continue
    # An earlier oval goes (the script run again).
    text = re.sub(r'\[sub_resource type="CapsuleShape2D" id="CapsuleShape2D_govde"\]\nradius = [^\n]*\nheight = [^\n]*\n\n', "", text)
    text = re.sub(r'\n\[node name="Govde"[\s\S]*$', "\n", text).rstrip("\n") + "\n"
    sub = f'[sub_resource type="CapsuleShape2D" id="CapsuleShape2D_govde"]\nradius = {ry}\nheight = {round(rx * 2, 1)}\n\n'
    i = text.index("[node ")
    text = text[:i] + sub + text[i:]
    text += (
        f'\n[node name="Govde" type="Area2D" parent="." unique_id={rng.randint(10**8, 2**31 - 1)}]\n'
        f"collision_layer = {BODY_LAYER}\ncollision_mask = 0\nmonitoring = false\nmonitorable = false\n\n"
        f'[node name="Oval" type="CollisionShape2D" parent="Govde" unique_id={rng.randint(10**8, 2**31 - 1)}]\n'
        f'rotation = 1.5707964\nshape = SubResource("CapsuleShape2D_govde")\ndebug_color = Color(1, 0.75, 0.2, 0.35)\n'
    )
    open(path, "w", encoding="utf-8", newline="\n").write(text)
    scenes += 1
print(len(bodies), "mob bodies,", scenes, "scenes")
