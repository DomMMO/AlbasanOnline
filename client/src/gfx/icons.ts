function shade(color: number, factor: number): string {
  const channel = (shift: number) => Math.min(255, Math.floor(((color >> shift) & 0xff) * factor));
  return `rgb(${channel(16)},${channel(8)},${channel(0)})`;
}

export const ICON_SIZE = 12;

/** Paints an icon into any 2D context at (offsetX, 0); `mirrored` flips it horizontally. */
export function paintIcon(ctx: CanvasRenderingContext2D, shape: IconShape, color: number, offsetX = 0, mirrored = false, offsetY = 0) {
  const palette: Record<string, string> = {
    k: "#120c10",
    m: shade(color, 1),
    l: shade(color, 1.35),
    d: shade(color, 0.6),
    w: "#ffffff",
    h: "#6b4423",
    g: "#e8c33a",
    n: "#cfe8f0",
    p: "#eadcb0",
    q: "#b49a68",
  };
  SHAPES[shape].forEach((row, y) => {
    for (let x = 0; x < row.length; x++) {
      const fill = palette[row[x]];
      if (!fill) continue;
      ctx.fillStyle = fill;
      ctx.fillRect(offsetX + (mirrored ? row.length - 1 - x : x), offsetY + y, 1, 1);
    }
  });
}

const cache = new Map<string, string>();

/** An item instance's icon: jewels take their rarity's colour, everything else its own. */
export function itemIconUrl(def: ItemDef, affixes?: Affix[]): string {
  if (!def.jewel) return iconUrl(def.icon.shape, def.icon.color);
  const color = Number.parseInt(RARITY_COLORS[itemRarity(def, affixes)].slice(1), 16);
  return iconUrl(def.icon.shape, color);
}

export function iconUrl(shape: IconShape, color: number): string {
  const key = `${shape}:${color}`;
  const cached = cache.get(key);
  if (cached) return cached;
  const canvas = document.createElement("canvas");
  canvas.width = ICON_SIZE;
  canvas.height = ICON_SIZE;
  paintIcon(canvas.getContext("2d")!, shape, color);
  const url = canvas.toDataURL();
  cache.set(key, url);
  return url;
}
